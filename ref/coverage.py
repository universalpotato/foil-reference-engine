"""Coverage report: which pool cards the reference engine supports (all Oracle text compiles).

    python3 -m ref.coverage [--out cards/coverage.md] [--json runs/coverage.json]

A card is supported when every face's Oracle text compiles (the compiler is strict: unknown
text raises Unsupported). Runtime-only gaps (rules that raise Unsupported when they happen) are
reported by the corpus and the fuzzer instead.
"""
import collections
import json
import os
import re
import sys

from .cards.model import DB
from . import Unsupported

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def card_status(name):
    try:
        card = DB.get(name)
    except KeyError as e:
        return False, f"unknown card: {e}"
    # Split cards (CR 709): instant/sorcery halves compile (ref/cards/batch9a.py); Rooms (709.5),
    # fuse and aftermath raise Unsupported as their faces compile.
    for f in card.faces:
        try:
            f.abilities()
        except Unsupported as e:
            return False, str(e)
        except Exception as e:  # noqa: BLE001
            return False, f"compiler error {type(e).__name__}: {e}"
    return True, ""


def pool():
    return [l.strip() for l in open(os.path.join(ROOT, "cards", "pool-maindeck-cards.txt")) if l.strip()]


def copies():
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    from carddata import main_deck_counts
    return main_deck_counts()[0]


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "cards", "coverage.md"))
    ap.add_argument("--json", default=os.path.join(ROOT, "runs", "coverage.json"))
    a = ap.parse_args(argv)
    names = pool()
    cp = copies()
    res = {}
    for n in names:
        ok, why = card_status(n)
        res[n] = {"supported": ok, "why": why, "copies": cp.get(n, 0)}
    sup = [n for n in names if res[n]["supported"]]
    tot_copies = sum(cp.get(n, 0) for n in names)
    sup_copies = sum(cp.get(n, 0) for n in sup)
    reasons = collections.Counter()
    for n in names:
        if not res[n]["supported"]:
            w = re.sub(r"^\[[^\]]*\] ", "", res[n]["why"])
            w = re.sub(r"'.*", "'…'", w)[:70]
            reasons[w] += cp.get(n, 0)
    os.makedirs(os.path.dirname(a.json), exist_ok=True)
    json.dump(res, open(a.json, "w"), indent=1, sort_keys=True)
    lines = ["# Reference engine coverage of the pool's main-deck cards", "",
             "Generated by `python3 -m ref.coverage`. A card counts as supported when all of its "
             "Oracle text compiles (the compiler is strict and fails loudly on anything else).", "",
             f"- Distinct cards: **{len(sup)} / {len(names)}** supported ({100 * len(sup) / len(names):.1f}%)",
             f"- Weighted by main-deck copies across {2561} pool lists: **{100 * sup_copies / max(1, tot_copies):.1f}%**", "",
             "## Most common reasons for unsupported cards (weighted by copies)", "",
             "| copies | reason |", "|---:|---|"]
    for r, v in reasons.most_common(40):
        lines.append(f"| {v} | {r.replace('|', '/')} |")
    lines += ["", "## Cards (sorted by copies)", "", "| card | copies | supported | reason |", "|---|---:|:---:|---|"]
    for n in sorted(names, key=lambda n: -cp.get(n, 0)):
        r = res[n]
        lines.append(f"| {n} | {r['copies']} | {'yes' if r['supported'] else 'no'} | {r['why'][:120].replace('|', '/')} |")
    open(a.out, "w").write("\n".join(lines) + "\n")
    print(f"supported {len(sup)}/{len(names)} cards; {100 * sup_copies / max(1, tot_copies):.1f}% of copies")


if __name__ == "__main__":
    main()
